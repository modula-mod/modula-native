import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname, resolve} from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'packages/design-contracts/tokens/design-contract.json');
const tsPath = resolve(root, 'packages/design-contracts/src/generated.ts');
const swiftPath = resolve(root, 'ios/Modula/DesignSystem/Tokens/GeneratedDesignContract.swift');
const contract = JSON.parse(await readFile(source, 'utf8'));

// Swift Double literal: always contains a decimal point.
const num = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

// Colour spec grammar:
//   "#RRGGBB"            -> sRGB hex
//   "rgb(r, g, b)"       -> 0...1 components
//   "white(a)" / "black(a)" -> Color.white/.black with opacity
//   "system:<UIColor>"   -> Color(uiColor: .<name>)
//   "semantic:<Color>"   -> Color.<name> (primary, secondary, white, black)
function swiftColor(spec) {
  let m;
  if ((m = /^#([0-9a-f]{6})$/i.exec(spec))) {
    const [r, g, b] = [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16));
    return `Color(red: ${r} / 255, green: ${g} / 255, blue: ${b} / 255)`;
  }
  if ((m = /^rgb\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\)$/.exec(spec))) return `Color(red: ${m[1]}, green: ${m[2]}, blue: ${m[3]})`;
  if ((m = /^(white|black)\(\s*([\d.]+)\s*\)$/.exec(spec))) return `Color.${m[1]}.opacity(${m[2]})`;
  if ((m = /^system:(\w+)$/.exec(spec))) return `Color(uiColor: .${m[1]})`;
  if ((m = /^semantic:(\w+)$/.exec(spec))) return `Color.${m[1]}`;
  throw new Error(`Unsupported colour spec: ${spec}`);
}

const themeNames = Object.keys(contract.themes);
const roles = Object.keys(contract.themes[themeNames[0]]);
for (const t of themeNames) {
  const keys = Object.keys(contract.themes[t]);
  if (keys.join() !== roles.join()) throw new Error(`Theme ${t} roles differ from ${themeNames[0]}`);
}
const indent = (s, n) => s.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');
const block = (name, obj) => `enum ${name} {\n${Object.entries(obj).map(([k, v]) => `    static let ${k} = ${num(v)}`).join('\n')}\n}`;
const themeLines = themeNames.map((t) => `static let ${t} = ThemeColors(\n${roles.map((r) => `    ${r}: ${swiftColor(contract.themes[t][r])}`).join(',\n')}\n)`).join('\n');
const typeRoles = Object.entries(contract.typography.roles)
  .map(([k, v]) => `static let ${k} = TypeRole(scale: ${num(v.scale)}, weight: .${v.weight})`).join('\n');
const elev = contract.elevation;
const elevLines = ['low', 'medium', 'high']
  .map((k) => `static let ${k} = Shadow(radius: ${num(elev[k].radius)}, y: ${num(elev[k].y)}, opacity: ${num(elev[k].opacity)})`).join('\n');

const ts = `// Generated by scripts/generate-design-contracts.mjs. Do not edit.\nexport const designContract = ${JSON.stringify(contract, null, 2)} as const;\nexport type DesignContract = typeof designContract;\n`;
const swift = `// Generated by scripts/generate-design-contracts.mjs. Do not edit.
import SwiftUI
import UIKit

enum GeneratedDesignContract {
    static let version = ${contract.version}
    static let accentDefault = "${contract.colors['accent.default']}"
    static let oledCanvas = "${contract.colors['canvas.oled']}"
    static let minimumTouchTarget = ${num(contract.density.minimumTouchTarget)}
    static let railLabelSeconds = ${num(contract.motion.railLabelSeconds)}

    /// Brand accent default (user-selectable accents override this at runtime).
    static let accentDefaultColor = ${swiftColor(contract.colors['accent.default'])}

    struct ThemeColors {
${roles.map((r) => `        let ${r}: Color`).join('\n')}
    }
    enum Theme {
${indent(themeLines, 8)}
    }

    struct TypeRole { let scale: Double; let weight: Font.Weight }
    enum Typography {
        static let baseSize = ${num(contract.typography.baseSize)}
${indent(typeRoles, 8)}
    }

${indent(block('Spacing', contract.spacing), 4)}
${indent(block('Radius', contract.radius), 4)}
${indent(block('Layout', contract.layout), 4)}

    struct Shadow { let radius: Double; let y: Double; let opacity: Double }
    enum Elevation {
        static let hairlineOpacity = ${num(elev.hairlineOpacity)}
${indent(elevLines, 8)}
    }

${indent(block('Motion', contract.motion), 4)}
}
`;
const outputs = [[tsPath, ts], [swiftPath, swift]];
if (process.argv.includes('--check')) {
  let current = true;
  for (const [path, expected] of outputs) current = (await readFile(path, 'utf8').catch(() => '')) === expected && current;
  if (!current) { console.error('Generated design contracts are out of date. Run npm run generate:design.'); process.exit(1); }
} else {
  for (const [path, content] of outputs) await writeFile(path, content);
}
