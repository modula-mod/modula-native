import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname, resolve} from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'packages/design-contracts/tokens/design-contract.json');
const tsPath = resolve(root, 'packages/design-contracts/src/generated.ts');
const swiftPath = resolve(root, 'ios/Modula/DesignSystem/Tokens/GeneratedDesignContract.swift');
const contract = JSON.parse(await readFile(source, 'utf8'));
const ts = `// Generated by scripts/generate-design-contracts.mjs. Do not edit.\nexport const designContract = ${JSON.stringify(contract, null, 2)} as const;\nexport type DesignContract = typeof designContract;\n`;
const swift = `// Generated by scripts/generate-design-contracts.mjs. Do not edit.\nimport Foundation\n\nenum GeneratedDesignContract {\n    static let version = ${contract.version}\n    static let accentDefault = "${contract.colors['accent.default']}"\n    static let oledCanvas = "${contract.colors['canvas.oled']}"\n    static let minimumTouchTarget = ${contract.density.minimumTouchTarget}.0\n    static let railLabelSeconds = ${contract.motion.railLabelSeconds}.0\n}\n`;
const outputs = [[tsPath, ts], [swiftPath, swift]];
if (process.argv.includes('--check')) {
  let current = true;
  for (const [path, expected] of outputs) current = (await readFile(path, 'utf8').catch(() => '')) === expected && current;
  if (!current) { console.error('Generated design contracts are out of date. Run npm run generate:design.'); process.exit(1); }
} else {
  for (const [path, content] of outputs) await writeFile(path, content);
}
