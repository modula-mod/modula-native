import Foundation
import os

private let registryLog = Logger(subsystem: "digital.modula.native", category: "MolibooCharacterRegistry")

// MARK: - MOL-03 canonical character registry (schema modula.moliboo.registry.1)
//
// One data file describes every Moliboo: identity (id/number/name/family), the 2D asset it renders from, its
// accessory-fit profile, the shared expression contract, motion profile, reactions and personality metadata, and
// the package that may later update its artwork. The native renderer stays the single runtime; characters are
// configured by data, so new characters, expressions and motions extend the file rather than the code.
// Generated by Tools/moliboo/registry/generate_registry.py from the roster in code; validated by
// MolibooRegistryValidator (unit tests) and runtime/tests/moliboo-registry.test.ts (CI).

/// The seven semantic expression states every Moliboo supports (MOL-03 §5).
enum MolibooSemanticExpression: String, CaseIterable, Codable, Sendable {
    case neutral, happy, excited, curious, sleepy, surprised, sad

    /// The shared 2D face/pose vocabulary each state renders with. Character-specific faces stay in the renderer.
    var mood: MascotMood {
        switch self {
        case .neutral: .idle
        case .happy: .happy
        case .excited: .excited
        case .curious: .curious
        case .sleepy: .sleepy
        case .surprised: .surprised
        case .sad: .sad
        }
    }

    var title: String { rawValue.prefix(1).uppercased() + rawValue.dropFirst() }
}

/// Reusable animation building blocks (MOL-03 §7). Motion profiles configure these; there is one engine.
enum MolibooAnimationPrimitive: String, CaseIterable, Codable, Sendable {
    case translate, rotate, scale, squashStretch, opacity, blink, layerOffset, glowIntensity, particleBurst, accessoryFollow, expressionTransition
}

struct MolibooMotionStep: Codable, Equatable, Sendable {
    var primitive: MolibooAnimationPrimitive
    var axis: String?
    var layer: String?
    var amplitude: Double
    var period: Double
}

struct MolibooMotionProfile: Codable, Equatable, Sendable {
    struct Reduced: Codable, Equatable, Sendable {
        var idle: [MolibooMotionStep]
        var allowBlink: Bool
        var note: String?
    }
    var familyId: String
    var language: String
    var idle: [MolibooMotionStep]
    var tempo: Double
    var reducedMotion: Reduced
}

struct MolibooRegistryReaction: Codable, Equatable, Sendable {
    var id: String?
    /// A `MascotMood` case name.
    var mood: String
    var primitive: MolibooAnimationPrimitive
    var burst: String?
    var durationMs: Int
    var line: String?
    var note: String?
    var afterSeconds: Int?
}

struct MolibooPersonality: Codable, Equatable, Sendable {
    var archetype: String
    var energy: Double
    var curiosity: Double
    var sociability: Double
    var description: String
    var disclaimer: String
}

struct MolibooRegistryFamily: Codable, Equatable, Sendable, Identifiable {
    var id: String
    var name: String
    var label: String
    var range: [Int]
    var world: String
    var wearable: Bool
    var motionProfile: String
}

struct MolibooRegistryCharacter: Codable, Equatable, Sendable, Identifiable {
    var id: String
    var number: Int
    var key: String
    var name: String
    var familyId: String
    var title: String
    var traits: [String]
    var assetVersion: String
    var rendering: String
    var baseAsset: String
    var body: String
    var parts: [String]
    var wearable: Bool
    var accessoryProfile: String?
    var expressions: [MolibooSemanticExpression]
    var animations: [String]
    var reactionSet: String
    var reactions: [String: MolibooRegistryReaction]
    var personality: MolibooPersonality
    var preferredMotion: String
    var idleSet: String
    var motionProfile: String
    var packageId: String

    var catalogueNumber: String { String(format: "%03d", number) }
    /// The built-in renderer kind, when this character ships in the binary.
    var kind: ModulaMascotKind? { ModulaMascotKind(rawValue: key) }
    var signature: MolibooRegistryReaction? { reactions["signature"] }
}

struct MolibooExpressionContract: Codable, Equatable, Sendable {
    struct Transition: Codable, Equatable, Sendable {
        var crossfadeMs: Int
        var reducedMotionCrossfadeMs: Int
        var interruptible: Bool
        var blink: String
    }
    var states: [MolibooSemanticExpression]
    var moodMap: [String: String]
    var transition: Transition
}

struct MolibooCharacterRegistry: Codable, Equatable, Sendable {
    static let schemaVersion = "modula.moliboo.registry.1"

    var schemaVersion: String
    var registryVersion: String
    var generator: String?
    var coordinateConvention: String
    var expressionContract: MolibooExpressionContract
    var animationPrimitives: [MolibooAnimationPrimitive]
    var motionProfiles: [String: MolibooMotionProfile]
    var families: [MolibooRegistryFamily]
    var characters: [MolibooRegistryCharacter]

    func character(id: String) -> MolibooRegistryCharacter? { characters.first { $0.id == id } }
    func character(key: String) -> MolibooRegistryCharacter? { characters.first { $0.key == key } }
    func character(number: Int) -> MolibooRegistryCharacter? { characters.first { $0.number == number } }
    func family(id: String) -> MolibooRegistryFamily? { families.first { $0.id == id } }
    func characters(in familyId: String) -> [MolibooRegistryCharacter] {
        characters.filter { $0.familyId == familyId }.sorted { $0.number < $1.number }
    }

    static func decode(_ data: Data) throws -> MolibooCharacterRegistry {
        try JSONDecoder().decode(MolibooCharacterRegistry.self, from: data)
    }
}

// MARK: - Loading (bundled, lazy, cached once)

enum MolibooRegistryStore {
    static let resourceName = "moliboo_registry"

    /// The bundled registry. Decoded lazily on first use (≈100 KB JSON), never on app launch.
    static let bundled: MolibooCharacterRegistry? = load(bundle: .main)

    static func load(bundle: Bundle) -> MolibooCharacterRegistry? {
        guard let url = bundle.url(forResource: resourceName, withExtension: "json") else {
            registryLog.error("moliboo_registry.json missing from bundle")
            return nil
        }
        do {
            return try MolibooCharacterRegistry.decode(Data(contentsOf: url))
        } catch {
            registryLog.error("moliboo_registry.json failed to decode: \(String(describing: error), privacy: .public)")
            return nil
        }
    }
}

extension ModulaMascotKind {
    /// Canonical registry entry (`moliboo.NNN`) for a built-in character.
    var registryEntry: MolibooRegistryCharacter? { MolibooRegistryStore.bundled?.character(key: rawValue) }
    var registryID: String { String(format: "moliboo.%03d", number) }
}

// MARK: - Validation (schema + referential integrity)

struct MolibooRegistryIssue: Equatable, Sendable, CustomStringConvertible {
    var characterId: String?
    var message: String
    var description: String { characterId.map { "\($0): \(message)" } ?? message }
}

enum MolibooRegistryValidator {
    static func isDigits(_ s: Substring) -> Bool { !s.isEmpty && s.allSatisfy(\.isASCII) && s.allSatisfy(\.isNumber) }
    static func isSemVer(_ s: String) -> Bool {
        let parts = s.split(separator: ".", omittingEmptySubsequences: false)
        return parts.count == 3 && parts.allSatisfy(isDigits)
    }
    static func hasNumberSuffix(_ s: String, prefix: String) -> Bool {
        guard s.hasPrefix(prefix) else { return false }
        let tail = s.dropFirst(prefix.count)
        return tail.count >= 3 && isDigits(tail)
    }
    static let knownMoods: Set<String> = ["idle", "typing", "happy", "pleased", "surprised", "sleepy", "thinking", "dizzy", "sad",
                                          "laughing", "speaking", "wave", "dance", "celebrate", "shy", "excited", "curious", "sit"]
    static let requiredReactions = ["tap", "doubleTap", "longPress", "horizontalDrag", "greeting", "equip", "idleTimeout", "foreground", "signature"]

    /// Validates a registry on its own. `fitProfiles` (when given) must contain every wearable character's profile.
    static func validate(_ r: MolibooCharacterRegistry, fitProfiles: Set<String>? = nil) -> [MolibooRegistryIssue] {
        var issues: [MolibooRegistryIssue] = []
        func fail(_ id: String?, _ m: String) { issues.append(MolibooRegistryIssue(characterId: id, message: m)) }

        if r.schemaVersion != MolibooCharacterRegistry.schemaVersion { fail(nil, "unsupported schemaVersion \(r.schemaVersion)") }
        if !isSemVer(r.registryVersion) { fail(nil, "registryVersion is not SemVer") }
        if Set(r.expressionContract.states) != Set(MolibooSemanticExpression.allCases) { fail(nil, "expression contract must list all seven states") }
        for (state, mood) in r.expressionContract.moodMap where MolibooSemanticExpression(rawValue: state) == nil || !knownMoods.contains(mood) {
            fail(nil, "expression contract maps \(state) to unknown mood \(mood)")
        }
        for (pid, p) in r.motionProfiles {
            if r.family(id: p.familyId) == nil { fail(nil, "motion profile \(pid) references unknown family \(p.familyId)") }
            if p.idle.isEmpty { fail(nil, "motion profile \(pid) has no idle steps") }
            let moving: Set<MolibooAnimationPrimitive> = [.translate, .rotate, .scale, .squashStretch]
            if p.reducedMotion.idle.contains(where: { moving.contains($0.primitive) && $0.amplitude > 0 }) {
                fail(nil, "motion profile \(pid) moves the body under Reduce Motion")
            }
        }

        var famIDs = Set<String>()
        var ranges: [(String, ClosedRange<Int>)] = []
        for f in r.families {
            if !famIDs.insert(f.id).inserted { fail(nil, "duplicate family \(f.id)") }
            guard f.range.count == 2, f.range[0] <= f.range[1] else { fail(nil, "family \(f.id) has an invalid range"); continue }
            let range = f.range[0]...f.range[1]
            if let clash = ranges.first(where: { $0.1.overlaps(range) }) { fail(nil, "family \(f.id) overlaps \(clash.0)") }
            ranges.append((f.id, range))
            if r.motionProfiles[f.motionProfile] == nil { fail(nil, "family \(f.id) motion profile \(f.motionProfile) is missing") }
        }

        var ids = Set<String>(), numbers = Set<Int>(), keys = Set<String>(), packages = Set<String>()
        for c in r.characters {
            let cid = c.id
            if !hasNumberSuffix(c.id, prefix: "moliboo.") { fail(cid, "id must look like moliboo.NNN") }
            if c.id != String(format: "moliboo.%03d", c.number) { fail(cid, "id does not match number \(c.number)") }
            if !ids.insert(c.id).inserted { fail(cid, "duplicate id") }
            if !numbers.insert(c.number).inserted { fail(cid, "duplicate number \(c.number)") }
            if !keys.insert(c.key).inserted { fail(cid, "duplicate key \(c.key)") }
            if !packages.insert(c.packageId).inserted { fail(cid, "duplicate packageId") }
            if c.name.trimmingCharacters(in: .whitespaces).isEmpty { fail(cid, "empty name") }
            if !hasNumberSuffix(c.packageId, prefix: "moliboo.character.") || !c.packageId.hasSuffix(String(format: ".%03d", c.number)) {
                fail(cid, "packageId \(c.packageId) does not match moliboo.character.NNN")
            }
            if !isSemVer(c.assetVersion) { fail(cid, "assetVersion is not SemVer") }
            if c.rendering != "2d" { fail(cid, "rendering must be 2d (3D stays dormant)") }
            if !(c.baseAsset.hasPrefix("native2d:") || c.baseAsset.hasPrefix("package:")) { fail(cid, "baseAsset \(c.baseAsset) has no known scheme") }
            guard let fam = r.family(id: c.familyId) else { fail(cid, "unknown family \(c.familyId)"); continue }
            if fam.range.count == 2, !(fam.range[0]...fam.range[1]).contains(c.number) { fail(cid, "number outside family \(fam.id) range") }
            if c.wearable != fam.wearable { fail(cid, "wearable flag disagrees with family \(fam.id)") }
            if c.wearable {
                guard let profile = c.accessoryProfile else { fail(cid, "wearable character has no accessoryProfile"); continue }
                if let fitProfiles, !fitProfiles.contains(profile) { fail(cid, "accessoryProfile \(profile) does not resolve") }
            } else if c.accessoryProfile != nil {
                fail(cid, "non-wearable character must not declare an accessoryProfile")
            }
            if Set(c.expressions) != Set(MolibooSemanticExpression.allCases) { fail(cid, "must support all seven expressions") }
            if r.motionProfiles[c.motionProfile] == nil { fail(cid, "motion profile \(c.motionProfile) is missing") }
            if c.motionProfile != fam.motionProfile { fail(cid, "motion profile differs from its family") }
            if !c.animations.contains(where: { $0.hasPrefix("idle/") }) { fail(cid, "no idle animation") }
            if !c.animations.contains(where: { $0.hasPrefix("signature/") }) { fail(cid, "no signature animation") }
            for name in requiredReactions where c.reactions[name] == nil { fail(cid, "missing \(name) reaction") }
            for (name, reaction) in c.reactions where !knownMoods.contains(reaction.mood) { fail(cid, "\(name) reaction uses unknown mood \(reaction.mood)") }
            if c.signature?.id?.isEmpty ?? true { fail(cid, "signature reaction has no id") }
            let p = c.personality
            for (label, v) in [("energy", p.energy), ("curiosity", p.curiosity), ("sociability", p.sociability)] where !(0...1).contains(v) {
                fail(cid, "personality.\(label) outside 0…1")
            }
            if p.description.isEmpty { fail(cid, "personality has no description") }
        }
        // Numbering inside every family is contiguous from its first number (no gaps that would hide a missing character).
        for f in r.families where f.range.count == 2 {
            let nums = r.characters(in: f.id).map { $0.number }
            if !nums.isEmpty, nums != Array(f.range[0]..<(f.range[0] + nums.count)) { fail(nil, "family \(f.id) numbering has gaps") }
        }
        return issues
    }
}
